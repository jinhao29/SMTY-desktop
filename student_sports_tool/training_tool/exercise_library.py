def list_categories():
    """获取所有动作分类名称。"""
    return list(EXERCISE_LIBRARY.keys())


def list_exercises(category):
    """获取指定分类下的所有动作。"""
    return EXERCISE_LIBRARY.get(category, [])


def find_exercise(name):
    """按动作名查找。返回 (分类, 组数, 次数, 要点) 或 None。"""
    for cat, exes in EXERCISE_LIBRARY.items():
        for ex in exes:
            if ex[0] == name:
                return (cat,) + ex
    return None
