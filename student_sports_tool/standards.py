    unit: str           # 显示单位（秒/分秒/次/米/cm/ml）
    direction: str      # MORE 值大越好 / LESS 值小越好
    boys_full: float     # 男生满分(100分)
    girls_full: float    # 女生满分(100分)
    boys_pass: float     # 男生及格(60分)
    girls_pass: float    # 女生及格(60分)


