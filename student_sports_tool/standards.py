# 年级编码 -> 完整显示名（0=学龄前无体测标准；13=中考2026新方案）
GRADE_OPTIONS = [
    ('0', '学龄前(3-7岁)'),
    ('1', '小学一年级'), ('2', '小学二年级'), ('3', '小学三年级'),
    ('4', '小学四年级'), ('5', '小学五年级'), ('6', '小学六年级'),
    ('7', '初一'), ('8', '初二'), ('9', '初三'),
    ('10', '高一'), ('11', '高二'), ('12', '高三'),
    ('13', '中考'),
]

_CN_NUM = {1: '一', 2: '二', 3: '三', 4: '四', 5: '五',
           6: '六', 7: '七', 8: '八', 9: '九', 10: '十'}


def grade_label(code) -> str:
    """年级编码转短显示名（与 Android Standards.gradeLabel 一致）。

    0/空 -> ''（UI 不显示年级）；1-6 -> 'X年级'；7-12 -> '初一'~'高三'；13 -> '中考'。
    """
    s = str(code).strip() if code is not None else ''
    g = int(s) if s.isdigit() else 0
    if g == 0 or s == '':
        return ''
    if 1 <= g <= 6:
        return f"{_CN_NUM.get(g, g)}年级"
    for c, label in GRADE_OPTIONS:
        if c == s:
            return label
    return f'年级{s}'


def grade_full_label(code) -> str:
    """年级编码转完整显示名（保留"小学"前缀）。"""
    s = str(code).strip() if code is not None else ''
    for c, label in GRADE_OPTIONS:
        if c == s:
            return label
    return '学龄前(3-7岁)' if s == '' else f'年级{s}'


def grade_code_from_label(label) -> str:
    """年级完整名 -> 编码（grade_full_label 的逆）。未匹配返回 None。"""
    t = (label or '').strip()
    if not t:
        return None
    for code, name in GRADE_OPTIONS:
        if name == t:
            return code
    if t == '学龄前':
        return '0'
    return None


def get_standards_by_grade(code):
    """按年级编码取标准列表（统一入口，与 Android getStandardsByGrade 一致）。

    0/空 -> []（学龄前无体测标准）；13 -> 中考2026；7-9 -> 初中；10-12 -> 高中；其余 -> 小学。
    """
    s = str(code).strip() if code is not None else ''
    g = int(s) if s.isdigit() else 0
    if g == 0:
        return []
    if g == 13:
        return ZHONGKAO_2026
    if 7 <= g <= 9:
        return JUNIOR.get(g, [])
    if 10 <= g <= 12:
        return SENIOR.get(g, [])
    return PRIMARY.get(g, [])


def archive_type_for_grade(code):
    """年级编码 -> (table_type, grade, sheet_tag)。

    用于把 Android 备份里的年级还原成 PC 档案类型。此前导入侧硬编码
    `table_type='primary', grade=None`，导致初高中与中考学员在 PC 端全部
    被当成小学生（拿不到对应学段标准）。

    编码体系与 Android GRADE_OPTIONS 一致：0/空=学龄前，1-6=小学，
    7-9=初中，10-12=高中，13=中考。
    """
    s = str(code).strip() if code is not None else ''
    g = int(s) if s.isdigit() else None
    if g == 13:
        return 'zhongkao', None, '中考2026'
    if g is not None and 7 <= g <= 9:
        return 'junior', g, grade_label(g)
    if g is not None and 10 <= g <= 12:
        return 'senior', g, grade_label(g)
    if g is not None and 1 <= g <= 6:
        return 'primary', g, f'{g}年级'
    return 'primary', None, 'Android导入'
